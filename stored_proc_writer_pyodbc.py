#!/usr/bin/env python3
"""Generate a pyodbc-based Python caller for an IBM i SQL procedure.

Usage:
  pip install pyodbc
  export IBM_I_ODBC='DRIVER={IBM i Access ODBC Driver};SYSTEM=host;UID=user;PWD=secret;'
  python stored_proc_writer_pyodbc.py MYLIB MYPROC MyProc

Only IN parameters are supported. OUT and INOUT are rejected deliberately:
pyodbc has no portable callproc()/output-parameter interface.
"""

import argparse
import keyword
import os
import re
from pathlib import Path

# These are the IBM i short catalog column names used by the original generator.
SQL = """SELECT PARMNO, PARMMODE, PARMNAME, DATA_TYPE
           FROM QSYS2.SYSPARMS
          WHERE SPECNAME = ? AND SPECSCHEMA = ?
          ORDER BY PARMNO"""

# The generated code is ordinary Python, not a second metaprogramming system.
TEMPLATE = '''"""Caller for {schema}.{procedure}. Generated by stored_proc_writer_pyodbc.py.

Set IBM_I_ODBC to a complete ODBC connection string before running.
"""
import os
import pyodbc


def call({signature}):
    """Call {schema}.{procedure}; return a list of result sets (lists of dicts)."""
    connection_string = os.environ["IBM_I_ODBC"]
    with pyodbc.connect(connection_string, autocommit=True) as connection:
        cursor = connection.cursor()
        cursor.execute({call_sql!r}{execute_args})
        result_sets = []
        while True:
            if cursor.description is not None:
                columns = [column[0] for column in cursor.description]
                result_sets.append([dict(zip(columns, row)) for row in cursor.fetchall()])
            if not cursor.nextset():
                break
        return result_sets
'''


def identifier(name, fallback, used):
    """Turn a catalog parameter name into a unique Python identifier."""
    base = re.sub(r"\W", "_", (name or fallback).strip().lower()) or fallback
    if base[0].isdigit() or keyword.iskeyword(base):
        base = "p_" + base
    candidate = base
    n = 2
    while candidate in used:
        candidate = f"{base}_{n}"
        n += 1
    used.add(candidate)
    return candidate


def generate(schema, procedure, parameters):
    unsupported = [p for p in parameters if p[1].strip().upper() != "IN"]
    if unsupported:
        details = ", ".join(f"{p[2] or p[0]} ({p[1]})" for p in unsupported)
        raise ValueError("OUT/INOUT parameters are not supported by this pyodbc caller: " + details)

    used = set()
    names = [identifier(p[2], f"parm{p[0]}", used) for p in parameters]
    schema, procedure = schema.upper(), procedure.upper()
    # Quote SQL identifiers to preserve exact names and avoid SQL injection.
    quoted = lambda name: '"' + name.replace('"', '""') + '"'
    qualified = f"{quoted(schema)}.{quoted(procedure)}"
    markers = ", ".join("?" for _ in names)
    call_sql = f"{{CALL {qualified}({markers})}}" if names else f"{{CALL {qualified}}}"
    return TEMPLATE.format(
        schema=schema, procedure=procedure,
        signature=", ".join(names), call_sql=call_sql,
        execute_args=(", " + ", ".join(names)) if names else "",
    )


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("schema")
    parser.add_argument("procedure", help="SQL specific name (SPECNAME), not necessarily routine name")
    parser.add_argument("module", help="Output Python module name, without .py")
    parser.add_argument("--output-dir", type=Path, default=Path("."))
    args = parser.parse_args()

    if not re.fullmatch(r"[A-Za-z_][A-Za-z_0-9]*", args.module):
        parser.error("module must be a valid Python identifier")
    if "IBM_I_ODBC" not in os.environ:
        parser.error("set IBM_I_ODBC to your ODBC connection string")

    import pyodbc
    with pyodbc.connect(os.environ["IBM_I_ODBC"], autocommit=True) as connection:
        cursor = connection.cursor()
        cursor.execute(SQL, args.procedure.upper(), args.schema.upper())
        parameters = cursor.fetchall()

    if not parameters:
        parser.error("no parameters found: cannot distinguish a zero-parameter procedure from an unknown SPECNAME")

    try:
        source = generate(args.schema, args.procedure, parameters)
    except ValueError as exc:
        parser.error(str(exc))
    args.output_dir.mkdir(parents=True, exist_ok=True)
    path = args.output_dir / (args.module + ".py")
    path.write_text(source, encoding="utf-8")
    print(f"Generated {path} ({len(parameters)} IN parameters)")


if __name__ == "__main__":
    main()
